

//unary: work with one variable
class Test
{
    public static void Main(string[] args)
    {
        int number =10;
        Console.WriteLine(number); //decimal format.  //10
        Console.WriteLine(++number);//pre increment. //11
        Console.WriteLine(number++);//post increment //11
        Console.WriteLine(number); //12
        Console.WriteLine(number--);//12
        Console.WriteLine(--number);//10

       

    }
}